/**
 * End-to-end proof that the Supabase schema, triggers and RLS policies behave.
 *
 * Creates a real auth user (service role), signs in as them, publishes a product
 * and leaves a draft, then reads as an anonymous client to confirm:
 *   · the profile trigger assigned a shop slug and the account type,
 *   · anonymous visitors see the published product but not the draft,
 *   · anonymous visitors cannot read profiles,
 *   · the seller cannot see or touch another seller's rows.
 *
 * Cleans up everything it creates.
 *
 *   node --import ./scripts/register.mjs scripts/supabase-rls-smoke.mjs
 */
import { loadEnv } from "./load-env.mjs";

loadEnv();

const url = (process.env.SUPABASE_URL ?? "").replace(/\/+$/, "");
const anon = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ?? "";
const service = process.env.SUPABASE_SERVICE_ROLE_KEY ?? "";

if (!url || !anon || !service) {
  console.error("Set SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY and SUPABASE_SERVICE_ROLE_KEY.");
  process.exit(1);
}

const { createClient } = await import("@supabase/supabase-js");

const admin = createClient(url, service, { auth: { persistSession: false } });
const stamp = Date.now();
const email = `rls-smoke-${stamp}@kandc.test`;
const password = "smoke-test-123456";

let failures = 0;
function check(label, ok, detail = "") {
  if (ok) console.log(`  ok   ${label}${detail ? ` — ${detail}` : ""}`);
  else {
    failures += 1;
    console.log(`  FAIL ${label}${detail ? ` — ${detail}` : ""}`);
  }
}

let userId = null;

try {
  console.log("\n1. Seller sign-up through Supabase Auth");

  const { data: created, error: createError } = await admin.auth.admin.createUser({
    email,
    password,
    email_confirm: true,
    user_metadata: {
      owner_name: "Smoke Seller",
      business_name: "Smoke Shop",
      account_type: "seller",
    },
  });

  if (createError) throw new Error(`createUser: ${createError.message}`);
  userId = created.user.id;
  check("auth user created", Boolean(userId), userId.slice(0, 8) + "…");

  const { data: profile, error: profileError } = await admin
    .from("profiles")
    .select("id, email, account_type, shop_slug, business_name")
    .eq("id", userId)
    .single();

  if (profileError) throw new Error(`profile lookup: ${profileError.message}`);
  check("profile row created by trigger", profile.email === email);
  check("account_type copied from metadata", profile.account_type === "seller");
  check("shop slug generated by trigger", Boolean(profile.shop_slug), profile.shop_slug ?? "");

  console.log("\n2. Seller writes their own catalogue");

  const seller = createClient(url, anon, { auth: { persistSession: false } });
  const { error: signInError } = await seller.auth.signInWithPassword({ email, password });
  if (signInError) throw new Error(`signIn: ${signInError.message}`);
  check("seller can sign in with email + password", true);

  const { error: productError } = await seller.from("products").insert([
    {
      seller_id: userId,
      name: "Smoke Published Bag",
      slug: `smoke-published-${stamp}`,
      description: "Visible to everyone",
      price_kobo: 4500000,
      publication_status: "published",
      availability: "available",
    },
    {
      seller_id: userId,
      name: "Smoke Draft Bag",
      slug: `smoke-draft-${stamp}`,
      description: "Should stay private",
      price_kobo: 1000000,
      publication_status: "draft",
      availability: "available",
    },
  ]);
  check("seller inserts products under RLS", !productError, productError?.message ?? "");

  console.log("\n3. Anonymous visitor");

  const anonClient = createClient(url, anon, { auth: { persistSession: false } });

  const { data: visible, error: visibleError } = await anonClient
    .from("products")
    .select("name, slug")
    .eq("seller_id", userId);
  check("anon sees the published product", (visible?.length ?? 0) === 1, visibleError?.message ?? "");
  check("anon does not see the draft", (visible ?? []).every((row) => !row.name.includes("Draft")));

  const { data: shopRow } = await anonClient
    .from("public_shops")
    .select("shop_slug, shop_name")
    .eq("id", userId)
    .maybeSingle();
  check("anon can read the storefront view", Boolean(shopRow?.shop_slug), shopRow?.shop_name ?? "");

  const { data: profileRows, error: profileReadError } = await anonClient
    .from("profiles")
    .select("id, email")
    .eq("id", userId);
  check(
    "anon cannot read profiles (RLS)",
    (profileRows?.length ?? 0) === 0,
    profileReadError?.message ?? "0 rows",
  );

  const { error: anonWriteError } = await anonClient.from("products").insert({
    seller_id: userId,
    name: "Hijack",
    slug: `hijack-${stamp}`,
    price_kobo: 1,
    publication_status: "published",
  });
  check("anon cannot insert products", Boolean(anonWriteError));

  console.log("\n4. Cross-seller isolation");

  const otherEmail = `rls-smoke-other-${stamp}@kandc.test`;
  const { data: otherCreated, error: otherError } = await admin.auth.admin.createUser({
    email: otherEmail,
    password,
    email_confirm: true,
    user_metadata: { owner_name: "Other Seller", business_name: "Other Shop", account_type: "seller" },
  });
  if (otherError) throw new Error(`createUser(other): ${otherError.message}`);

  const other = createClient(url, anon, { auth: { persistSession: false } });
  await other.auth.signInWithPassword({ email: otherEmail, password });

  // Published products are public by design — another seller may read them.
  const { data: visibleToOther } = await other
    .from("products")
    .select("name")
    .eq("seller_id", userId);
  check(
    "another seller sees only the published product",
    (visibleToOther?.length ?? 0) === 1 &&
      (visibleToOther ?? []).every((row) => !row.name.includes("Draft")),
  );

  const { data: updatedRows, error: updateError } = await other
    .from("products")
    .update({ price_kobo: 1 })
    .eq("seller_id", userId)
    .select("id");
  check(
    "another seller cannot edit these products",
    (updatedRows?.length ?? 0) === 0 || Boolean(updateError),
  );

  const { data: deletedRows, error: deleteError } = await other
    .from("products")
    .delete()
    .eq("seller_id", userId)
    .select("id");
  check(
    "another seller cannot delete these products",
    (deletedRows?.length ?? 0) === 0 || Boolean(deleteError),
  );

  const { data: untouched } = await admin
    .from("products")
    .select("price_kobo, publication_status")
    .eq("seller_id", userId);
  check(
    "the products are unchanged",
    (untouched?.length ?? 0) === 2 &&
      (untouched ?? []).every((row) => row.price_kobo !== 1),
  );

  await admin.auth.admin.deleteUser(otherCreated.user.id);

  console.log("\n5. Customer accounts");

  const customerEmail = `rls-smoke-customer-${stamp}@kandc.test`;
  const { data: customer, error: customerError } = await admin.auth.admin.createUser({
    email: customerEmail,
    password,
    email_confirm: true,
    user_metadata: { owner_name: "Smoke Buyer", account_type: "customer" },
  });
  if (customerError) throw new Error(`createUser(customer): ${customerError.message}`);

  const { data: customerProfile } = await admin
    .from("profiles")
    .select("account_type, shop_slug")
    .eq("id", customer.user.id)
    .single();

  check("customer account type stored", customerProfile?.account_type === "customer");
  check("customers get no shop slug", customerProfile?.shop_slug === null);

  await admin.auth.admin.deleteUser(customer.user.id);
} catch (error) {
  failures += 1;
  console.error(`\nFAILED: ${error.message}`);
} finally {
  if (userId) {
    await admin.auth.admin.deleteUser(userId).catch(() => {});
    console.log("\nCleaned up the smoke-test seller (products cascade).");
  }
}

console.log(
  failures === 0
    ? "\nRLS smoke test passed — the database enforces what the app expects."
    : `\n${failures} check(s) failed.`,
);
process.exit(failures === 0 ? 0 : 1);
